#!/usr/bin/env python3
"""Compute the Git-native content inventory of one tree, read-only.

The inventory is derived from Git on demand and is never committed (ADR-0038):
a commit SHA already binds every tracked path, mode, object type, and object ID,
so a tracked copy of that inventory only restates the commit and has to be
regenerated by every change. `FORBIDDEN_TRACKED_PATH` names the retired
committed manifest, which `scripts/validate_git_integrity.py` refuses.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

FORBIDDEN_TRACKED_PATH = "GIT_TREE_MANIFEST.json"
SCHEMA_VERSION = "l9.git-tree-manifest/2.0.0"
OBJECT_ID = re.compile(r"[0-9a-f]{40}|[0-9a-f]{64}")


def _git_bytes(root: Path, *args: str) -> bytes:
    completed = subprocess.run(
        ["git", *args],
        cwd=root,
        check=False,
        capture_output=True,
    )
    if completed.returncode != 0:
        message = completed.stderr.decode("utf-8", "replace").strip()
        if not message:
            message = completed.stdout.decode("utf-8", "replace").strip()
        raise RuntimeError(message)
    return completed.stdout


def _git_text(root: Path, *args: str) -> str:
    return _git_bytes(root, *args).decode("utf-8", "strict").strip()


def resolve_tree(root: Path, treeish: str) -> str:
    """Resolve a treeish to its tree object ID, refusing anything git would read as an option.

    The treeish comes from the command line. A value starting with ``-`` reaches
    git as an option, not a revision; ``--end-of-options`` stops that during
    resolution, and only the resolved object ID is passed on to ``ls-tree``.
    """

    if not treeish or treeish.startswith("-"):
        raise ValueError(f"treeish must name a revision or tree, not an option: {treeish!r}")
    object_id = _git_text(root, "rev-parse", "--verify", "--end-of-options", f"{treeish}^{{tree}}")
    if not OBJECT_ID.fullmatch(object_id):
        raise ValueError(f"treeish did not resolve to a tree object ID: {treeish!r}")
    return object_id


def collect_tree_entries(root: Path, treeish: str) -> tuple[dict[str, str], ...]:
    """Return path, mode, object type, and Git object ID for every entry of one tree."""

    output = _git_bytes(root, "ls-tree", "-r", "--full-tree", "-z", resolve_tree(root, treeish))
    entries: list[dict[str, str]] = []
    for raw_record in output.split(b"\0"):
        if not raw_record:
            continue
        metadata, separator, raw_path = raw_record.partition(b"\t")
        if not separator:
            raise RuntimeError("git ls-tree emitted a malformed record")
        metadata_parts = metadata.decode("ascii").split()
        if len(metadata_parts) != 3:
            raise RuntimeError("git ls-tree emitted malformed object metadata")
        mode, object_type, object_id = metadata_parts
        entries.append(
            {
                "path": raw_path.decode("utf-8", "surrogateescape"),
                "mode": mode,
                "object_type": object_type,
                "git_object_id": object_id,
            }
        )
    return tuple(sorted(entries, key=lambda item: item["path"]))


def entries_sha256(entries: tuple[dict[str, str], ...]) -> str:
    canonical = json.dumps(
        entries,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(canonical).hexdigest()


def build_manifest(root: Path, treeish: str) -> dict[str, Any]:
    entries = collect_tree_entries(root, treeish)
    return {
        "schema_version": SCHEMA_VERSION,
        "content_scope": "all tracked Git entries of the tree",
        "tree_sha": resolve_tree(root, treeish),
        "entry_count": len(entries),
        "entries_sha256": entries_sha256(entries),
        "entries": list(entries),
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Print the Git content inventory of a tree. Writes nothing to the repository."
    )
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument(
        "--treeish", default="HEAD", help="Git treeish to inventory (default HEAD)."
    )
    args = parser.parse_args()
    root = args.root.resolve()
    # S8705: validate that root is a real git-tracked directory before passing to subprocess
    if not root.is_dir():
        sys.stderr.write(f"ERROR: --root is not a directory: {root}\n")
        return 1
    try:
        payload = build_manifest(root, args.treeish)
    except ValueError as exc:
        sys.stderr.write(f"ERROR: {exc}\n")
        return 2
    print(json.dumps(payload, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
